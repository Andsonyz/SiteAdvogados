import { test, expect } from '@playwright/test'

test('desktop vertical scrolling advances and reverses the horizontal image panels', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const section = page.locator('.horizontal-journey')
  await expect(section).toBeAttached()
  await page.evaluate(async () => { await document.fonts.ready; await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))) })
  await expect(section).toHaveClass(/is-scroll-driven/)
  const rail = section.locator('.rail-viewport')
  const start = await section.evaluate(el => el.getBoundingClientRect().top + scrollY - Number.parseFloat(getComputedStyle(el).getPropertyValue('--journey-top')))
  await page.evaluate(y => window.scrollTo({ top: y + 450, behavior: 'instant' }), start)
  await expect.poll(() => rail.evaluate(el => Math.abs(el.scrollLeft - 450))).toBeLessThan(3)
  const beforeQueuedEvent = await page.evaluate(y => {
    window.scrollTo({ top: y, behavior: 'instant' })
    document.querySelector('.journey-rail .rail-viewport')!.dispatchEvent(new Event('scroll'))
    return scrollY
  }, start + 550)
  expect(Math.abs(beforeQueuedEvent - (start + 550))).toBeLessThan(3)
  const pinned = await section.locator('.journey-sticky').boundingBox()
  expect(pinned!.y).toBeGreaterThanOrEqual(80)
  expect(pinned!.y).toBeLessThan(130)
  const distance = await rail.evaluate(el => el.scrollWidth - el.clientWidth)
  await page.evaluate(y => window.scrollTo({ top: y, behavior: 'instant' }), start + distance + 300)
  await expect.poll(() => rail.evaluate(el => el.scrollLeft)).toBeGreaterThan(distance - 3)
  expect((await section.locator('.journey-sticky').boundingBox())!.y).toBeLessThan(80)
  await page.evaluate(y => window.scrollTo({ top: y + 450, behavior: 'instant' }), start)
  await expect.poll(() => rail.evaluate(el => Math.abs(el.scrollLeft - 450))).toBeLessThan(3)
  await rail.focus(); await page.keyboard.press('Home')
  await expect.poll(() => rail.evaluate(el => el.scrollLeft)).toBeLessThan(3)
  await page.evaluate(y => window.scrollTo({ top: y, behavior: 'instant' }), start)
  await expect.poll(() => rail.evaluate(el => el.scrollLeft)).toBeLessThan(3)
  for (const img of await section.locator('img').all()) await img.evaluate((el: HTMLImageElement) => { el.loading = 'eager'; return el.decode() })
  expect(await section.locator('img').count()).toBe(3)
  expect(errors).toEqual([])
})

test('mobile panels support buttons, keyboard and dragging while the page stays vertical', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#principios')
  const section = page.locator('.horizontal-journey')
  await expect(section).toBeAttached()
  await expect(section).not.toHaveClass(/is-scroll-driven/)
  const rail = section.locator('.rail-viewport')
  await section.getByRole('button', { name: 'Próximo item' }).click()
  await expect.poll(() => rail.evaluate(el => el.scrollLeft)).toBeGreaterThan(200)
  await rail.focus(); await page.keyboard.press('End')
  await expect(section.getByRole('button', { name: 'Próximo item' })).toBeDisabled()
  await page.keyboard.press('Home')
  await expect.poll(() => rail.evaluate(el => el.scrollLeft)).toBeLessThan(3)
  const box = (await rail.boundingBox())!
  await page.mouse.move(box.x + box.width * .8, box.y + box.height / 2)
  await page.mouse.down(); await page.mouse.move(box.x + box.width * .2, box.y + box.height / 2, { steps: 12 }); await page.mouse.up()
  await expect.poll(() => rail.evaluate(el => el.scrollLeft)).toBeGreaterThan(100)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('reduced motion and enlarged content remain readable without pinned scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/#principios')
  const section = page.locator('.horizontal-journey')
  await expect(section).toHaveClass(/is-scroll-driven/)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(section).not.toHaveClass(/is-scroll-driven/)
  await page.setViewportSize({ width: 320, height: 700 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  await expect(section.locator('h3')).toHaveCount(3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await section.locator('.rail-viewport').focus(); await page.keyboard.press('End')
  await expect(section.getByRole('button', { name: 'Próximo item' })).toBeDisabled()
})

test('resizing a later desktop panel to mobile preserves the current section', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/#principios')
  const section = page.locator('.horizontal-journey')
  await expect(section).toHaveClass(/is-scroll-driven/)
  await page.evaluate(async () => { await document.fonts.ready; await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))) })
  await section.evaluate(el => {
    const start = el.getBoundingClientRect().top + scrollY - parseFloat(getComputedStyle(el).getPropertyValue('--journey-top'))
    window.scrollTo({ top: start + 1800, behavior: 'instant' })
  })
  await expect.poll(() => section.locator('.rail-viewport').evaluate(el => el.scrollLeft)).toBeGreaterThan(1700)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(section).not.toHaveClass(/is-scroll-driven/)
  await expect.poll(async () => (await section.boundingBox())!.y).toBeGreaterThanOrEqual(70)
  expect((await section.boundingBox())!.y).toBeLessThan(130)
})

test('direct desktop anchors remain below the header after horizontal layout settles', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  for (const id of ['sobre', 'atuacao', 'atendimento', 'duvidas']) {
    await page.goto(`/#${id}`)
    await expect(page.locator(`#${id}`)).toBeAttached()
    await page.evaluate(async () => { await document.fonts.ready; await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))) })
    const position = await page.locator(`#${id}`).evaluate(el => ({ top: el.getBoundingClientRect().top, header: document.querySelector('.site-header')!.getBoundingClientRect().height }))
    expect(position.top).toBeGreaterThanOrEqual(position.header - 2)
    expect(position.top).toBeLessThan(position.header + 80)
  }
})
